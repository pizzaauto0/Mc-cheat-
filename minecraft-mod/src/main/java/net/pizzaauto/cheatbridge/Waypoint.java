package net.pizzaauto.cheatbridge;

public class Waypoint {
    public final String label;
    public final double x;
    public final double y;
    public final double z;

    public Waypoint(String label, double x, double y, double z) {
        this.label = label;
        this.x = x;
        this.y = y;
        this.z = z;
    }
}
